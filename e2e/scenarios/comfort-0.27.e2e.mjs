// 0.27.0 daily comfort: a heading's text shows in "title and text", change many items at
// once, duplicate an item, restore one item's older version.
import { gitIn, gitRepo, launch, newItem, scenario } from '../harness.mjs'

await scenario('E2E comfort', async (ctx) => {
  const { repo } = gitRepo('comfort')
  const t = (ctx.t = await launch({ openPath: repo }))
  const { win, check } = t
  await win.getByRole('button', { name: 'Open repository…' }).click()
  await win.getByRole('button', { name: 'Create requirements folder' }).click()
  await win.locator('.first-run').waitFor()
  const editor = win.locator('.editor')
  const add = async (type, title, text) => {
    await newItem(win, type)
    await win.getByPlaceholder('Short name of the requirement').fill(title)
    if (text) await editor.getByRole('textbox', { name: 'Text', exact: true }).fill(text)
    await win.getByRole('button', { name: 'Save', exact: true }).click()
    await win.getByRole('button', { name: 'Saved ✓' }).waitFor()
  }
  await add('information', 'Chapter 1', 'This chapter explains the door system.')
  await add('system-requirement', 'Door lock', 'The door shall lock within 2 s.')
  await add('system-requirement', 'Window lift', 'The window shall close within 4 s.')
  const row = (title) => win.locator('.table__row', { hasText: title }).first()

  console.log('A heading shows its text too')
  await win.getByRole('button', { name: 'View', exact: true }).click()
  await win.getByRole('dialog', { name: 'View' }).getByRole('radio', { name: 'Rows: title and text' }).check()
  await win.keyboard.press('Escape')
  await row('Chapter 1').locator('.table__main-text', { hasText: 'explains the door system' }).waitFor()
  check(true, 'with "title and text", a Heading / Information item shows its text')

  console.log('Change many items at once')
  await win.getByRole('button', { name: 'Close', exact: true }).first().click().catch(() => {})
  await row('Door lock').click({ modifiers: ['Control'] })
  await row('Window lift').click({ modifiers: ['Control'] })
  await row('Window lift').click({ button: 'right' })
  await win.getByRole('menuitem', { name: 'Change the 2 chosen items…' }).click()
  const dlg = win.getByRole('dialog', { name: 'Change 2 items' })
  await dlg.getByLabel('What to change').selectOption({ label: 'Priority' })
  await dlg.getByLabel('New value').selectOption('High')
  await t.shot('comfort-1-change-many')
  await dlg.getByRole('button', { name: 'Change', exact: true }).click()
  await dlg.getByText('2 changed.').waitFor()
  check(true, 'both items changed; the dialog says so')
  await dlg.getByRole('button', { name: 'Close', exact: true }).last().click()
  await row('Door lock').click()
  check((await editor.getByLabel('Priority').inputValue()) === 'High', 'the editor shows the new priority')

  console.log('Duplicate')
  await row('Door lock').click({ button: 'right' })
  await win.getByRole('menuitem', { name: 'Duplicate', exact: true }).click()
  await win.locator('.table-notice--ok', { hasText: 'Copy made' }).waitFor()
  check((await win.locator('.table__row', { hasText: 'Door lock' }).count()) === 2, 'a copy appears right below the original')
  await t.shot('comfort-2-duplicated')

  console.log('Restore an older version of one item')
  gitIn(repo, 'add', '-A')
  gitIn(repo, 'commit', '-q', '-m', 'First version')
  await row('Window lift').click()
  await win.getByPlaceholder('Short name of the requirement').fill('Window lift fast')
  await win.getByRole('button', { name: 'Save', exact: true }).click()
  await win.getByRole('button', { name: 'Saved ✓' }).waitFor()
  // a restore never goes over an uncommitted change: commit the edit first
  gitIn(repo, 'commit', '-q', '-am', 'Faster window')
  await editor.getByRole('tab', { name: 'History' }).click()
  const versions = win.getByRole('list', { name: 'Versions' })
  await versions.locator('.history__entry', { hasText: 'First version' }).click()
  await editor.getByRole('button', { name: 'Restore this version' }).click()
  await t.shot('comfort-3-restore-ask')
  await editor.getByRole('button', { name: 'Restore', exact: true }).click()
  await editor.getByText('Restored. Review it under Changes').waitFor()
  await editor.getByRole('tab', { name: 'Details' }).click()
  await win.waitForFunction(() => document.querySelector('.editor input[placeholder="Short name of the requirement"]')?.value === 'Window lift')
  check(true, 'the old title is back in the editor')
})
