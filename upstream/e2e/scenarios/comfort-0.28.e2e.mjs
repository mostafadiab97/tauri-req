// 0.28.0 daily comfort part 2: templates per type, sentence patterns and writing hints, saved views.
import { gitRepo, launch, newItem, scenario } from '../harness.mjs'

await scenario('E2E comfort 2', async (ctx) => {
  const { repo } = gitRepo('comfort2')
  const t = (ctx.t = await launch({ openPath: repo }))
  const { win, check } = t
  await win.getByRole('button', { name: 'Open repository…' }).click()
  await win.getByRole('button', { name: 'Create requirements folder' }).click()
  await win.locator('.first-run').waitFor()
  const editor = win.locator('.editor')
  const text = editor.getByRole('textbox', { name: 'Text', exact: true })

  console.log('A new test case starts with its template')
  await newItem(win, 'test-case')
  check((await text.inputValue()).startsWith('Preconditions:'), 'the text box holds the Test Case template')
  await win.getByPlaceholder('Short name of the requirement').fill('Door test')
  await win.getByRole('button', { name: 'Save', exact: true }).click()
  await win.getByRole('button', { name: 'Saved ✓' }).waitFor()

  console.log('Writing hints and a sentence pattern')
  await newItem(win, 'system-requirement')
  await win.getByPlaceholder('Short name of the requirement').fill('Door lock')
  await text.fill('The door locks fast.')
  const hints = editor.getByRole('note', { name: 'Writing hints' })
  await hints.waitFor()
  const said = await hints.textContent()
  check(said.includes('"fast" is vague') && said.includes('No "shall"'), 'hints name the vague word and the missing "shall"')
  await t.shot('comfort2-1-hints')
  await text.fill('')
  await editor.getByLabel('Insert a pattern').selectOption({ index: 2 })
  check((await text.inputValue()) === 'When <trigger>, the <system> shall <response>.', 'the pattern is inserted into the text')
  await text.fill('When the car moves, the door shall lock within 2 s.')
  check((await hints.count()) === 0, 'a clear requirement shows no hints')
  await win.getByRole('button', { name: 'Save', exact: true }).click()
  await win.getByRole('button', { name: 'Saved ✓' }).waitFor()

  console.log('Saved views')
  await win.getByLabel('Search').fill('door lock')
  await win.getByRole('button', { name: 'Saved views' }).click()
  await win.getByRole('menuitem', { name: 'Save the current view…' }).click()
  const dlg = win.getByRole('dialog', { name: 'Save the current view' })
  await dlg.getByLabel('Name').fill('Locks')
  await dlg.getByRole('radio', { name: /For the team/ }).check()
  await t.shot('comfort2-2-save-view')
  await dlg.getByRole('button', { name: 'Save view' }).click()
  await win.locator('.table-notice--ok', { hasText: 'saved for the team' }).waitFor()
  await win.getByLabel('Search').fill('')
  await win.getByRole('button', { name: 'Saved views' }).click()
  await t.shot('comfort2-3-views-menu')
  await win.getByRole('menuitem', { name: 'Locks', exact: true }).click()
  check((await win.getByLabel('Search').inputValue()) === 'door lock', 'applying the view brings its search back')
  check((await win.getByRole('button', { name: /^Changes/ }).first().textContent()).includes('settings'), 'the team view is a change to commit (settings)')

  console.log('Reset the view')
  await win.getByRole('button', { name: 'Saved views' }).click()
  await win.getByRole('menuitem', { name: /^Reset the view/ }).click()
  check((await win.getByLabel('Search').inputValue()) === '', 'Reset the view clears the search')
  await win.locator('.table-notice--ok', { hasText: 'View reset' }).waitFor()
})
